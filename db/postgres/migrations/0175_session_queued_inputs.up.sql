-- 0175_session_queued_inputs
-- Durable queue for user input that met a session with a run in flight: Web and
-- CLI follow-ups, and platform messages that arrive while the bot is busy.
-- Redis kept follow-ups for 24 hours and lost them on restart; a user's message
-- must survive both, so the queue is a table. Only claims are stored: the
-- payload never carries a credential, and whoever starts the turn signs a new
-- one.
--
-- A batch is the inputs one run answers together. Claiming stamps them with a
-- batch_id, and the run is admitted under the invocation id 'queued:<batch_id>',
-- which session_runs_invocation_unique refuses a second time. A claim that
-- outlives its lease is taken again under the same batch_id, so a crash between
-- admission and the consumed write cannot admit the batch twice.
--
-- Migrating down drops every input that is still waiting; drain the queue
-- (state = 'queued') before rolling back to a release that reads Redis.

CREATE TABLE IF NOT EXISTS public.session_queued_inputs (
    id                     UUID        NOT NULL,
    team_id                UUID        NOT NULL DEFAULT public.memoh_current_team_id()
                                       REFERENCES public.teams(id) ON DELETE RESTRICT,
    bot_id                 UUID        NOT NULL,
    session_id             UUID        NOT NULL,
    -- 'follow_up' is drained by the server, 'platform_busy' by the channel
    -- process. The value picks the drainer; no code branches on it otherwise.
    origin                 TEXT        NOT NULL,
    -- Retry identity of the input. A redelivered message or a repeated request
    -- finds its first row instead of adding a second.
    invocation_id          TEXT        NOT NULL,
    -- Inputs that share a merge key and are next to each other in the queue are
    -- answered by one run; an empty key is an input that stands alone. Callers
    -- use the sender, so a batch never mixes people.
    merge_key              TEXT        NOT NULL DEFAULT '',
    payload                JSONB       NOT NULL,
    position               BIGINT      NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    enqueued_during_run_id TEXT        NOT NULL DEFAULT '',
    -- When the platform delivered the input. A reply is judged against it, not
    -- against the moment the input leaves the queue. NULL is an arrival time
    -- nobody recorded (an input moved over from Redis, or one typed into the
    -- queue panel): its reply window counts as closed.
    received_at            TIMESTAMPTZ,
    state                  TEXT        NOT NULL DEFAULT 'queued',
    batch_id               UUID,
    claim_token            UUID,
    claimed_until          TIMESTAMPTZ,
    -- Invocation id of the run that took the input, once it did.
    run_invocation_id      TEXT,
    error_code             TEXT,
    created_at             TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at             TIMESTAMPTZ NOT NULL DEFAULT now(),
    settled_at             TIMESTAMPTZ,
    PRIMARY KEY (team_id, id),
    CONSTRAINT session_queued_inputs_invocation_key
        UNIQUE (team_id, session_id, invocation_id),
    CONSTRAINT session_queued_inputs_origin_check
        CHECK (origin IN ('follow_up', 'platform_busy')),
    CONSTRAINT session_queued_inputs_state_check
        CHECK (state IN ('queued', 'claimed', 'promoting', 'promoted', 'consumed', 'cancelled')),
    CONSTRAINT session_queued_inputs_claim_check
        CHECK (state <> 'claimed' OR (batch_id IS NOT NULL AND claim_token IS NOT NULL AND claimed_until IS NOT NULL)),
    CONSTRAINT session_queued_inputs_bot_id_fkey
        FOREIGN KEY (team_id, bot_id)
        REFERENCES public.bots(team_id, id) ON DELETE CASCADE,
    CONSTRAINT session_queued_inputs_session_id_fkey
        FOREIGN KEY (team_id, session_id)
        REFERENCES public.bot_sessions(team_id, id) ON DELETE CASCADE
);

-- A session's waiting inputs in order: the admission barrier, the queue panel
-- and the claim all read this.
CREATE INDEX IF NOT EXISTS session_queued_inputs_waiting
    ON public.session_queued_inputs (team_id, session_id, position)
    WHERE state IN ('queued', 'claimed');

-- The sweep asks which sessions have something for its origin to drain.
CREATE INDEX IF NOT EXISTS session_queued_inputs_sweep
    ON public.session_queued_inputs (team_id, origin, session_id)
    WHERE state IN ('queued', 'claimed');

ALTER TABLE public.session_queued_inputs ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.session_queued_inputs FORCE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS session_queued_inputs_team_select ON public.session_queued_inputs;
DROP POLICY IF EXISTS session_queued_inputs_team_insert ON public.session_queued_inputs;
DROP POLICY IF EXISTS session_queued_inputs_team_update ON public.session_queued_inputs;
DROP POLICY IF EXISTS session_queued_inputs_team_delete ON public.session_queued_inputs;

CREATE POLICY session_queued_inputs_team_select ON public.session_queued_inputs
    FOR SELECT USING (team_id = public.memoh_current_team_id());
CREATE POLICY session_queued_inputs_team_insert ON public.session_queued_inputs
    FOR INSERT WITH CHECK (team_id = public.memoh_current_team_id());
CREATE POLICY session_queued_inputs_team_update ON public.session_queued_inputs
    FOR UPDATE
    USING (team_id = public.memoh_current_team_id())
    WITH CHECK (team_id = public.memoh_current_team_id());
CREATE POLICY session_queued_inputs_team_delete ON public.session_queued_inputs
    FOR DELETE USING (team_id = public.memoh_current_team_id());
